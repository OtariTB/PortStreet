"""Master Code Sharder & Dispatch Table Generator for NFS ProStreet.

Partitions 31,995 recompiled functions from nfs.exe into 32 modular C translation
units (gen/shard_0000.c .. gen/shard_0031.c) and generates the master indirect
dispatch table (gen/fntab.h and gen/fntab.c).

Features:
- O(1) direct text dispatch via g_dtab[addr - 0x00401000] (DISPATCH_TEXT_SIZE = 0x00567000).
- Secondary O(log N) switch dispatch in dispatch_indirect() for SecuROM / non-text functions.
- Chunked startup initialization in fntab_init() (<1ms initialization time).
- Local Register Promotion (LREGS) and Dead-Flag Elimination (FLAGABI) across all shards.
- Complete forward declarations in gen/fntab.h enabling clean multi-threaded / modular C compilation.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sys
import time
from typing import Any, Sequence

WORKSPACE = Path(__file__).resolve().parent.parent
if str(WORKSPACE) not in sys.path:
    sys.path.insert(0, str(WORKSPACE))

from tools.clean_drm import EXPECTED_NFS_EXE_SHA256
from tools.lift_catalog import FunctionLifter

DISPATCH_TEXT_BASE = 0x00401000
DISPATCH_TEXT_SIZE = 0x00567000
DISPATCH_TEXT_END = DISPATCH_TEXT_BASE + DISPATCH_TEXT_SIZE


def generate_fntab_header(functions: Sequence[dict[str, Any]]) -> str:
    """Generates the C header file gen/fntab.h with all function prototypes."""
    lines = [
        "/* Master Function Dispatch Table & Prototypes for NFS ProStreet.",
        " * Auto-generated by tools/generate_shards.py.",
        " */",
        "#ifndef PROSTREET_FNTAB_H",
        "#define PROSTREET_FNTAB_H",
        "",
        "#include <stdio.h>",
        "#include <stdint.h>",
        '#include "runtime/cpu.h"',
        '#include "runtime/memory.h"',
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f"/* Forward declarations ({len(functions)} functions) */",
    ]

    for f in functions:
        lines.append(f"void sub_{f['address']:08x}(CPU *c);")

    lines.extend([
        "",
        "/* Master dispatch table initialization (call during engine boot) */",
        "void fntab_init(void);",
        "",
        "/* Unresolved indirect dispatch tracking */",
        "typedef struct {",
        "    uint32_t target_va;",
        "    uint32_t call_site_ret;",
        "    uint32_t esp;",
        "    uint32_t count;",
        "} unresolved_dispatch_t;",
        "",
        "/* Secondary indirect dispatch handler */",
        "void dispatch_indirect(struct CPU *c, uint32_t addr);",
        "void dispatch_tail(struct CPU *c);",
        "uint32_t fntab_get_unresolved_count(void);",
        "uint32_t fntab_get_unresolved_unique(void);",
        "const unresolved_dispatch_t *fntab_get_unresolved_entry(uint32_t idx);",
        "void fntab_reset_unresolved(void);",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* PROSTREET_FNTAB_H */\n",
    ])
    return "\n".join(lines)


def generate_fntab_source(
    functions: Sequence[dict[str, Any]],
    chunk_size: int = 2500,
    trampoline_data: dict[str, Any] | None = None,
) -> str:
    """Generates the C implementation file gen/fntab.c with g_dtab and dispatch_indirect."""
    text_funcs = [f for f in functions if DISPATCH_TEXT_BASE <= f["address"] < DISPATCH_TEXT_END]
    non_text_funcs = [f for f in functions if not (DISPATCH_TEXT_BASE <= f["address"] < DISPATCH_TEXT_END)]

    lines = [
        "/* Master Function Dispatch Table Implementation for NFS ProStreet.",
        " * Auto-generated by tools/generate_shards.py.",
        " */",
        '#include "gen/fntab.h"',
        "#include <stdio.h>",
        "#include <stdlib.h>",
        "#include <string.h>",
        "",
        "/* Primary direct dispatch table for .text section (BSS) */",
        "guest_fn_t g_dtab[DISPATCH_TEXT_SIZE];",
        "",
    ]

    # Chunked initializers
    chunk_names = []
    for chunk_idx, i in enumerate(range(0, len(text_funcs), chunk_size)):
        chunk = text_funcs[i : i + chunk_size]
        fname = f"fntab_init_chunk_{chunk_idx}"
        chunk_names.append(fname)
        lines.append(f"static void {fname}(void) {{")
        for f in chunk:
            offset = f["address"] - DISPATCH_TEXT_BASE
            lines.append(f"    g_dtab[0x{offset:08x}u] = sub_{f['address']:08x};")
        lines.append("}\n")

    # Trampoline entries in g_dtab and non-text dispatch_indirect aliases
    t_entries = []
    non_text_aliases: dict[int, int] = {}
    if trampoline_data:
        fn_addrs = {f["address"] for f in functions}
        all_records = list(trampoline_data.get("trampolines", [])) + list(
            trampoline_data.get("securom_bridges", [])
        )
        seen_text_off: set[int] = set()
        for t in all_records:
            t_va = int(t.get("target_va", 0))
            if t_va not in fn_addrs:
                continue
            for alias_key in ("site_va", "stub_va"):
                a_va = int(t.get(alias_key, 0))
                if not a_va or a_va == t_va:
                    continue
                if DISPATCH_TEXT_BASE <= a_va < DISPATCH_TEXT_END:
                    off = a_va - DISPATCH_TEXT_BASE
                    if off not in seen_text_off and a_va not in fn_addrs:
                        seen_text_off.add(off)
                        t_entries.append((off, t_va))
                elif a_va not in fn_addrs and a_va not in non_text_aliases:
                    non_text_aliases[a_va] = t_va
        t_entries.sort(key=lambda x: x[0])

    if t_entries:
        lines.append("static void fntab_init_trampolines(void) {")
        for off, target in t_entries:
            lines.append(f"    g_dtab[0x{off:08x}u] = sub_{target:08x};")
        lines.append("}\n")

    lines.append("void fntab_init(void) {")
    if t_entries:
        lines.append("    fntab_init_trampolines();")
    for cname in chunk_names:
        lines.append(f"    {cname}();")
    lines.append("}\n")

    # Secondary indirect dispatch
    lines.extend([
        "#define MAX_UNRESOLVED_RECORDED 64",
        "static uint32_t s_unresolved_count = 0;",
        "static uint32_t s_unresolved_unique = 0;",
        "static unresolved_dispatch_t s_unresolved_dispatches[MAX_UNRESOLVED_RECORDED];",
        "",
        "uint32_t fntab_get_unresolved_count(void) {",
        "    return s_unresolved_count;",
        "}",
        "",
        "uint32_t fntab_get_unresolved_unique(void) {",
        "    return s_unresolved_unique;",
        "}",
        "",
        "const unresolved_dispatch_t *fntab_get_unresolved_entry(uint32_t idx) {",
        "    if (idx < s_unresolved_unique) return &s_unresolved_dispatches[idx];",
        "    return (const unresolved_dispatch_t *)0;",
        "}",
        "",
        "void fntab_reset_unresolved(void) {",
        "    s_unresolved_count = 0;",
        "    s_unresolved_unique = 0;",
        "    memset(s_unresolved_dispatches, 0, sizeof(s_unresolved_dispatches));",
        "}",
        "",
        "void dispatch_indirect(struct CPU *c, uint32_t addr) {",
        "    if (c) cpu_trace_record(c, addr);",
        "    uint32_t off = addr - DISPATCH_TEXT_BASE;",
        "    if (off < DISPATCH_TEXT_SIZE) {",
        "        guest_fn_t fn = g_dtab[off];",
        "        if (fn) { fn(c); return; }",
        "    }",
        "    switch (addr) {",
    ])

    for f in non_text_funcs:
        lines.append(f"    case 0x{f['address']:08x}u: sub_{f['address']:08x}(c); return;")
    for alias_va in sorted(non_text_aliases):
        target_va = non_text_aliases[alias_va]
        lines.append(f"    case 0x{alias_va:08x}u: sub_{target_va:08x}(c); return;")

    lines.extend([
        "    default:",
        "        if (c) c->eip = addr;",
        "        PS_HOST_ATOMIC_FETCH_ADD32(&s_unresolved_count, 1u);",
        "        uint32_t ret_addr = (c && c->esp >= 0x00140000u && c->esp < 0x00400000u) ? MR32(c->esp) : 0;",
        "        int found = 0;",
        "        for (uint32_t i = 0; i < s_unresolved_unique; i++) {",
        "            if (s_unresolved_dispatches[i].target_va == addr) {",
        "                PS_HOST_ATOMIC_FETCH_ADD32(&s_unresolved_dispatches[i].count, 1u);",
        "                found = 1;",
        "                break;",
        "            }",
        "        }",
        "        if (!found && s_unresolved_unique < MAX_UNRESOLVED_RECORDED) {",
        "            uint32_t slot = PS_HOST_ATOMIC_FETCH_ADD32(&s_unresolved_unique, 1u);",
        "            if (slot < MAX_UNRESOLVED_RECORDED) {",
        "                s_unresolved_dispatches[slot].target_va = addr;",
        "                s_unresolved_dispatches[slot].call_site_ret = ret_addr;",
        "                s_unresolved_dispatches[slot].esp = c ? c->esp : 0;",
        "                s_unresolved_dispatches[slot].count = 1;",
        "            }",
        "        }",
        '        fprintf(stderr, "[DISPATCH] Unresolved indirect target: 0x%08x (esp=0x%08x [esp]=0x%08x)\\n", addr, c ? c->esp : 0, ret_addr);',
        "        return;",
        "    }",
        "}",
        "",
        "void dispatch_tail(struct CPU *c) {",
        "    dispatch_indirect(c, c->eip);",
        "}\n",
    ])

    return "\n".join(lines)


def generate_shards(
    catalog: dict[str, Any],
    raw_exe: bytes,
    out_dir: Path,
    num_shards: int = 32,
    max_functions: int | None = None,
    enable_lregs: bool = True,
    enable_flagabi: bool = True,
    flifter: FunctionLifter | None = None,
    progress_callback: Any = None,
    include_manual_overrides: bool | None = None,
) -> dict[str, Any]:
    """Generates all C shards and the master dispatch table.

    Returns:
        Manifest dictionary summarizing generated files and counts.
    """
    out_dir.mkdir(parents=True, exist_ok=True)

    if include_manual_overrides is None:
        include_manual_overrides = len(raw_exe) >= DISPATCH_TEXT_SIZE

    known_addrs = {f["address"] for f in catalog["functions"]}
    all_funcs = list(catalog["functions"])
    if include_manual_overrides:
        from tools.manual_overrides import ADDITIONAL_FUNCTIONS
        for va in ADDITIONAL_FUNCTIONS:
            if va not in known_addrs:
                all_funcs.append({"address": va, "blocks": []})
    sorted_funcs = sorted(all_funcs, key=lambda f: f["address"])
    if max_functions is not None:
        sorted_funcs = sorted_funcs[:max_functions]

    total_funcs = len(sorted_funcs)
    num_shards = max(1, min(num_shards, total_funcs))

    # Initialize function lifter
    if flifter is None:
        flifter = FunctionLifter(
            raw_exe,
            catalog,
            enable_lregs=enable_lregs,
            enable_flagabi=enable_flagabi,
        )

    # 1. Generate gen/fntab.h
    fntab_h_path = out_dir / "fntab.h"
    fntab_h_content = generate_fntab_header(sorted_funcs)
    fntab_h_path.write_text(fntab_h_content, encoding="utf-8")

    # 2. Generate gen/fntab.c
    t_path = WORKSPACE / "research" / "local" / "phase1" / "securom_trampolines.json"
    trampoline_data = None
    if t_path.is_file():
        trampoline_data = json.loads(t_path.read_text(encoding="utf-8"))
    fntab_c_path = out_dir / "fntab.c"
    fntab_c_content = generate_fntab_source(sorted_funcs, trampoline_data=trampoline_data)
    fntab_c_path.write_text(fntab_c_content, encoding="utf-8")

    # 3. Generate individual shards
    shard_manifests = []
    total_shard_bytes = 0

    for s_idx in range(num_shards):
        start_i = s_idx * total_funcs // num_shards
        end_i = (s_idx + 1) * total_funcs // num_shards
        shard_funcs = sorted_funcs[start_i:end_i]

        min_addr = shard_funcs[0]["address"] if shard_funcs else 0
        max_addr = shard_funcs[-1]["address"] if shard_funcs else 0
        fname = f"shard_{s_idx:04d}.c"
        shard_path = out_dir / fname

        shard_lines = [
            f"/* Shard {s_idx:04d}: Functions 0x{min_addr:08x}..0x{max_addr:08x} ({len(shard_funcs)} functions)",
            " * Auto-generated by tools/generate_shards.py for NFS ProStreet.",
            " */",
            "#define PROSTREET_LREGS 1",
            "#include <stdio.h>",
            '#include "gen/fntab.h"',
            "",
        ]

        for func in shard_funcs:
            c_code = flifter.lift_function(
                func["address"],
                enable_lregs=enable_lregs,
                enable_flagabi=enable_flagabi,
            )
            shard_lines.append(c_code)

        shard_content = "\n".join(shard_lines)
        shard_path.write_text(shard_content, encoding="utf-8")
        file_size = shard_path.stat().st_size
        total_shard_bytes += file_size

        entry = {
            "index": s_idx,
            "filename": fname,
            "function_count": len(shard_funcs),
            "min_address": f"0x{min_addr:08x}",
            "max_address": f"0x{max_addr:08x}",
            "file_size_bytes": file_size,
        }
        shard_manifests.append(entry)

        if progress_callback:
            progress_callback(s_idx, num_shards, entry)

    manifest = {
        "schema": "nfsu-shards-manifest-v1",
        "total_functions": total_funcs,
        "num_shards": num_shards,
        "total_c_size_bytes": total_shard_bytes + fntab_c_path.stat().st_size + fntab_h_path.stat().st_size,
        "fntab_h": "fntab.h",
        "fntab_c": "fntab.c",
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "shards": shard_manifests,
    }

    manifest_path = out_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    return manifest


def lift_single_function(
    func_va: int,
    raw_exe: bytes,
    out_dir: Path,
    trampoline_data: dict[str, Any] | None = None,
) -> Path:
    """Lifts a single function from raw_exe and inserts/updates it in the appropriate shard."""
    import re
    from tools.build_catalog import CatalogBuilder
    from tools.lift_catalog import FunctionLifter

    builder = CatalogBuilder(raw_exe, trampoline_data or {"trampolines": []})
    fn_dict, calls = builder.disassemble_function(func_va, set())
    if not fn_dict:
        raise ValueError(f"Failed to disassemble function at 0x{func_va:08x}")

    cat = {
        "image_base": 0x400000,
        "code_start": 0x401000,
        "code_end": 0x967000,
        "functions": [fn_dict],
    }
    flifter = FunctionLifter(raw_exe, cat, enable_lregs=True, enable_flagabi=True)
    c_code = flifter.lift_function(func_va)

    shard_files = sorted(out_dir.glob("shard_*.c"))
    if not shard_files:
        raise FileNotFoundError(f"No shard files found in {out_dir}")

    target_shard = None
    for sf in shard_files:
        content = sf.read_text(encoding="utf-8")
        addrs = [int(m, 16) for m in re.findall(r"void sub_([0-9a-f]{8})\(", content)]
        if not addrs:
            continue
        if min(addrs) <= func_va <= max(addrs):
            target_shard = sf
            break

    if target_shard is None:
        for sf in shard_files:
            content = sf.read_text(encoding="utf-8")
            addrs = [int(m, 16) for m in re.findall(r"void sub_([0-9a-f]{8})\(", content)]
            if addrs and max(addrs) >= func_va:
                target_shard = sf
                break

    if target_shard is None:
        target_shard = shard_files[-1]

    content = target_shard.read_text(encoding="utf-8")
    fn_name = f"sub_{func_va:08x}"
    if f"void {fn_name}(CPU *c)" in content:
        pattern = re.compile(rf"void {fn_name}\(CPU \*c\) \{{.*?^\}}", re.MULTILINE | re.DOTALL)
        content = pattern.sub(c_code.strip(), content)
    else:
        matches = list(re.finditer(r"^void sub_([0-9a-f]{8})\(CPU \*c\)", content, re.MULTILINE))
        inserted = False
        for m in matches:
            other_va = int(m.group(1), 16)
            if other_va > func_va:
                pos = m.start()
                content = content[:pos] + c_code + "\n" + content[pos:]
                inserted = True
                break
        if not inserted:
            content = content.rstrip() + "\n\n" + c_code + "\n"

    target_shard.write_text(content, encoding="utf-8")

    # Update fntab.h
    fntab_h = out_dir / "fntab.h"
    if fntab_h.is_file():
        h_text = fntab_h.read_text(encoding="utf-8")
        decl = f"void sub_{func_va:08x}(CPU *c);"
        if decl not in h_text:
            matches = list(re.finditer(r"^void sub_([0-9a-f]{8})\(CPU \*c\);", h_text, re.MULTILINE))
            inserted = False
            for m in matches:
                other_va = int(m.group(1), 16)
                if other_va > func_va:
                    pos = m.start()
                    h_text = h_text[:pos] + decl + "\n" + h_text[pos:]
                    inserted = True
                    break
            if not inserted:
                h_text = h_text.replace("/* Master dispatch table", decl + "\n\n/* Master dispatch table")
            fntab_h.write_text(h_text, encoding="utf-8")

    # Update fntab.c
    fntab_c = out_dir / "fntab.c"
    if fntab_c.is_file():
        c_text = fntab_c.read_text(encoding="utf-8")
        slot = func_va - DISPATCH_TEXT_BASE
        entry = f"    g_dtab[0x{slot:08x}u] = sub_{func_va:08x};"
        if entry.strip() not in c_text:
            matches = list(re.finditer(r"^\s+g_dtab\[0x([0-9a-f]{8})u\] = sub_[0-9a-f]{8};", c_text, re.MULTILINE))
            inserted = False
            for m in matches:
                other_slot = int(m.group(1), 16)
                if other_slot > slot:
                    pos = m.start()
                    c_text = c_text[:pos] + entry + "\n" + c_text[pos:]
                    inserted = True
                    break
            if not inserted:
                c_text = c_text.replace("void fntab_init(void)", entry + "\n}\n\nvoid fntab_init(void)")
            fntab_c.write_text(c_text, encoding="utf-8")

    return target_shard


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate modular C shards and master dispatch table.")
    parser.add_argument("--num-shards", type=int, default=32, help="Number of C shards (default: 32)")
    parser.add_argument("--out-dir", type=str, default="gen", help="Output directory (default: gen)")
    parser.add_argument("--max-functions", type=int, default=None, help="Optional limit on functions to lift")
    parser.add_argument("--lift-single", type=lambda x: int(x, 0), default=None, help="VA of single function to lift and update in-place")
    args = parser.parse_args()

    cfg_path = WORKSPACE / "config" / "local.json"
    if not cfg_path.is_file():
        sys.exit(f"Config not found at {cfg_path}")

    cfg = json.loads(cfg_path.read_text())
    exe_path = Path(cfg["game_root"]) / "Need For Spped - Pro Street" / "nfs.exe"
    if not exe_path.is_file():
        sys.exit(f"Target executable not found at {exe_path}")

    raw_exe = exe_path.read_bytes()
    sha256 = hashlib.sha256(raw_exe).hexdigest()
    if sha256 != EXPECTED_NFS_EXE_SHA256:
        sys.exit(f"Executable SHA-256 mismatch: {sha256}")

    out_dir = WORKSPACE / args.out_dir

    if args.lift_single is not None:
        target_va = args.lift_single
        print(f"Lifting single function 0x{target_va:08x} from {exe_path.name}...")
        shard = lift_single_function(target_va, raw_exe, out_dir)
        print(f"Successfully lifted and updated 0x{target_va:08x} in {shard.name}, fntab.h, and fntab.c.")
        return

    catalog_path = WORKSPACE / "research" / "local" / "phase1" / "catalog.json"
    if not catalog_path.is_file():
        sys.exit(f"Catalog not found at {catalog_path}")

    print(f"Loading catalog from {catalog_path.name}...")
    catalog = json.loads(catalog_path.read_text())
    total_funcs = len(catalog["functions"])
    total_blocks = sum(len(f.get("blocks", [])) for f in catalog["functions"])
    print(f"Catalog loaded: {total_funcs} functions across {total_blocks} basic blocks.")

    out_dir = WORKSPACE / args.out_dir
    print(f"Generating {args.num_shards} shards in {out_dir}...")
    t0 = time.time()

    def on_progress(s_idx: int, total_shards: int, entry: dict[str, Any]) -> None:
        elapsed = time.time() - t0
        pct = (s_idx + 1) * 100 // total_shards
        print(f"  [{pct:3d}%] Shard {entry['index']:04d}: {entry['filename']} ({entry['function_count']} fns, "
              f"{entry['min_address']}..{entry['max_address']}, {entry['file_size_bytes'] / 1024:.1f} KB) "
              f"[{elapsed:.1f}s]")

    manifest = generate_shards(
        catalog=catalog,
        raw_exe=raw_exe,
        out_dir=out_dir,
        num_shards=args.num_shards,
        max_functions=args.max_functions,
        progress_callback=on_progress,
    )

    elapsed = time.time() - t0
    mb = manifest["total_c_size_bytes"] / (1024 * 1024)
    print(f"\nSuccessfully generated {manifest['num_shards']} shards + fntab.c/h ({manifest['total_functions']} functions, "
          f"{mb:.2f} MB C source) in {elapsed:.1f}s ({manifest['total_functions'] / elapsed:.1f} fns/sec).")


if __name__ == "__main__":
    main()
